def test_transient_table_has_uuid_dataset_chain(app, monkeypatch):
    """string (src_uuid_dataset) -> uuid (uuid_dataset) : l'ancien nom n'est plus créé."""

    def no_store(*args, **kwargs):
        raise AssertionError("uuid_dataset ne doit pas passer par un store")

