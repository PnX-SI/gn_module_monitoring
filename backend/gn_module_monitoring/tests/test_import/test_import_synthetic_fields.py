"""
Champs synthétiques de l'import (`get_synthetic_field_specs`) chargés en mode strict, et identifiants
propres (`get_identifier_bib_fields`).

Les identifiants propres (origine, identifiant, UUID : site, visit, observation) ne passent plus par
`EntityFieldConfigSchema` ni par un store : ce sont des entrées de bib_fields directes, avec leur type
de colonne transitoire (`column_type`, type SQLAlchemy).

Un store integer exige un widget qui renvoie `int` : le widget `number` ne le renvoie que si
`step` est entier (`NumberWidget.get_api_type`). Sans `step`, il renvoie `float` et le mode strict
rejette l'incohérence (config/entities/fields.py).
"""

