@pytest.mark.parametrize("entity_code", ["site", "visit", "observation"])
def test_identifier_column_types_are_set_without_store(app, monkeypatch, entity_code):
    """La table transitoire lit `column_type` : ni store, ni `get_column_type`, ni lecture de config."""

    def no_store(*args, **kwargs):
        raise AssertionError("un identifiant ne doit pas passer par un store")

    monkeypatch.setattr(sql_module, "get_field_store", no_store)
    protocol_data = {entity_code: {"fields": get_identifier_bib_fields(entity_code, 1)}}
    # Module de données (configuration v3) : même code que test_import_transient_table.py
    table = get_imports_table_metadata("demo", protocol_data)
    suffix = _suffix(entity_code)
    assert isinstance(table.c[f"id_{suffix}"].type, Integer)
    assert isinstance(table.c[f"uuid_{suffix}"].type, Uuid)
    assert f"src_id_{suffix}" not in table.c
    assert f"src_uuid_{suffix}" in table.c


def test_visit_parent_id_is_found_by_name_in_destination_fields():
    """
    Le transfert retrouve `id_base_site` par son nom dans les champs de destination de la visite :
    `get_destination_fields` le retient même sans colonne mappée (lien parent).
    """

    class _Field:
        def __init__(self, bib):
            self.name_field = bib["name_field"]
            self.dest_field = bib["dest_field"]
            self.multi = False

    class _EntityField:
        def __init__(self, field):
            self.field = field

    class _Entity:
        code = "visit"

    visit_bibs = get_identifier_bib_fields("visit", 1)
    # id_base_site (parent) n'est pas une colonne d'identifiant de la visite : c'est un champ du site
    site_id = _Field({"name_field": "id_base_site", "dest_field": "id_base_site"})
    visit_fields = [_EntityField(_Field(bib)) for bib in visit_bibs] + [
        _EntityField(site_id),
        _EntityField(_Field({"name_field": "id_dataset", "dest_field": "id_dataset"})),
    ]
    entity = _Entity()
    entity.fields = visit_fields
    imprt = type("Imprt", (), {"fieldmapping": {}, "columns": []})()

    selected = EntityImportActionsUtils.get_destination_fields(imprt, entity)

    assert "id_base_site" in {field.name_field for field in selected}
    assert "id_base_visit" in {field.name_field for field in selected}


# Champs synthétiques (géométrie, id_dataset) : pris dans la configuration par défaut de l'entité.
@pytest.mark.parametrize("entity_code", ["site", "visit"])
def test_synthetic_fields_come_from_default_entity_config(app, entity_code):
    from gn_module_monitoring.modules import get_module

    entity = get_module("generic").entities[entity_code]
    specs = get_synthetic_field_specs(entity_code, entity)
    assert specs, entity_code
    for spec in specs:
        assert "config" not in spec, spec["key"]
        assert spec["key"] in entity.data["fields"], spec["key"]
    bib_fields = load_synthetic_fields(entity, specs, 1, {})
    for bib_field, spec in zip(bib_fields, specs):
        widget_type = entity.data["fields"][spec["key"]]["widget"]["type"]
        assert bib_field["type_field"] == widget_type, spec["key"]


# Nom sans attribut natif : seule la cohérence widget/store est testée.
TEST_FIELD_NAME = "id_test_entier"


def test_number_widget_without_step_is_rejected_with_integer_store(app, monkeypatch):
    monkeypatch.setitem(app.config[MODULE_CODE], "STRICT", True)
    entity = make_entity("site", {})
    config = {
        "store": {"type": "integer"},
        "widget": {"type": "number", "hidden": True},
    }
    with schema_context(entity=entity):
        with pytest.raises(ValidationError, match="Incohérence de type"):
            EntityFieldConfigSchema().load({"name": TEST_FIELD_NAME, **config})


