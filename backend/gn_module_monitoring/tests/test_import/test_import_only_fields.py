IDENTIFIER_ENTITIES = ["site", "visit", "observation"]


def make_entity(entity_code, data):
    entity = object.__new__(ENTITY_MAP[entity_code])
    entity.data = data
    return entity


def import_only_entity(entity_code):
    data = {"geom_field_name": "geom"} if entity_code == "site" else {}
    return make_entity(entity_code, data)


def by_name(bib_fields):
    return {field["name_field"]: field for field in bib_fields}


def _direct(entity_code, id_destination=1, entity=None):
    if entity is None:
        entity = import_only_entity(entity_code)
    return get_import_only_bib_fields(entity_code, entity, id_destination)


def identifiers(entity_code, id_destination=1):
    """Identifiants propres (origine, identifiant, UUID) parmi les champs directs."""
    suffix = _suffix(entity_code)
    names = {
        entity_import_field_name(entity_code, f"id_{suffix}_origin"),
        f"id_{suffix}",
        entity_import_field_name(entity_code, f"uuid_{suffix}"),
    }
    return [f for f in _direct(entity_code, id_destination) if f["name_field"] in names]


def coordinates(entity_code, entity, id_destination):
    """Coordonnées x, y parmi les champs directs."""
    return [
        f
        for f in _direct(entity_code, id_destination, entity)
        if f["name_field"] in ("s__x", "s__y")
    ]


def uuid_dataset_bibs(entity_code, id_destination=1):
    return [f for f in _direct(entity_code, id_destination) if f["name_field"] == "uuid_dataset"]




@pytest.mark.parametrize("entity_code", IDENTIFIER_ENTITIES)
def test_identifiers_are_direct_bib_fields_without_store(entity_code):
    bib_fields = identifiers(entity_code, 42)
    assert len(bib_fields) == 3
    for field in bib_fields:
        assert "store" not in field
        assert "column_type" in field
        assert field["mandatory"] is False
        assert field["mandatory_conditions"] is None
        assert field["optional_conditions"] is None
        assert field["id_destination"] == 42


@pytest.mark.parametrize("entity_code", IDENTIFIER_ENTITIES)
def test_identifier_id_is_autogenerated_hidden_integer(entity_code):
    field = by_name(identifiers(entity_code, 1))[f"id_{_suffix(entity_code)}"]
    assert field["autogenerated"] is True
    assert field["display"] is False
    assert field["source_field"] is None
    assert field["dest_field"] == field["name_field"]
    assert field["column_type"] is Integer
    assert field["type_field"] == "number"
    assert field["type_field_params"]["step"] == 1
    assert field["type_field_params"]["hidden"] is True


@pytest.mark.parametrize("entity_code", IDENTIFIER_ENTITIES)
def test_identifier_origin_is_imported_text_without_destination(entity_code):
    name = entity_import_field_name(entity_code, f"id_{_suffix(entity_code)}_origin")
    field = by_name(identifiers(entity_code, 1))[name]
    assert field["autogenerated"] is False
    assert field["display"] is True
    assert field["source_field"] == name
    assert field["dest_field"] is None
    assert field["column_type"] is String


@pytest.mark.parametrize("entity_code", IDENTIFIER_ENTITIES)
def test_identifier_uuid_is_imported_uuid(entity_code):
    name = entity_import_field_name(entity_code, f"uuid_{_suffix(entity_code)}")
    field = by_name(identifiers(entity_code, 1))[name]
    assert field["source_field"] == f"src_{name}"
    assert field["dest_field"] == name
    assert field["column_type"] is Uuid


def _suffix(entity_code):
    return entity_code if entity_code == "observation" else f"base_{entity_code}"


