def _direct_bib_field(
    name_field: str,
    fr_label: str,
    id_destination: int,
    *,
    type_field: str,
    type_field_params: dict,
    column_type,
    source_field,
    dest_field,
    autogenerated: bool = False,
    display: bool = True,
    mandatory: bool = False,
    optional_conditions=None,
) -> dict:
    """
    Entrée de bib_fields directe d'un champ import only (identifiant, coordonnée, UUID de JDD), sans
    store ni `EntityFieldConfigSchema` (voir get_import_only_bib_fields).
    """
    return {
        "name_field": name_field,
        "fr_label": fr_label,
        "eng_label": None,
        "mandatory": mandatory,
        "autogenerated": autogenerated,
        "display": display,
        "mnemonique": None,
        "type_field": type_field,
        "type_field_params": type_field_params,
        "source_field": source_field,
        "dest_field": dest_field,
        "multi": False,
        "id_destination": id_destination,
        "mandatory_conditions": None,
        "optional_conditions": optional_conditions,
        # Type SQLAlchemy de la colonne de destination dans la table transitoire. Non persisté dans
        # bib_fields (retiré par insert_bib_field) ; lu par get_imports_table_metadata.
        "column_type": column_type,
    }


def get_import_only_bib_fields(entity_code: str, entity, id_destination: int) -> list:
    """
    Champs import only en entrées de bib_fields directes (sans store, sans `EntityFieldConfigSchema`) :

    - identifiants propres (site, visit, observation) :
      - identifiant d'origine (`id_<entité>_origin`) : lu dans le fichier (`source_field`), sans destination ;
      - identifiant (`id_<entité>`) : autogénéré, masqué, sans source, destination = son nom ;
      - UUID (`uuid_<entité>`) : lu dans le fichier (`src_<nom>`), destination = son nom ;
    - coordonnées `x` et `y` (site ayant une géométrie) : lues dans le fichier, sans destination ;
      requises sauf si la géométrie est fournie (`optional_conditions`) ;
    - UUID du JDD (visit) : lu dans le fichier (`src_<nom>`), destination = son nom. `id_dataset` est
      rempli par `check_datasets` (cœur) à partir de cet UUID.

    Le lien à l'entité, et à son parent pour les enfants (`is_parent_link`), est créé par
    `insert_entity_field_relations` à partir de `fields` de l'entité, comme pour les autres champs.
    Le type de colonne transitoire est un type SQLAlchemy donné ici (`column_type`).
    """
    fields = []

    if entity_code in ("site", "visit", "observation"):
        label_entity = (
            f"{entity_code.capitalize()}e" if entity_code == "visit" else entity_code.capitalize()
        )
        suffix = entity_code if entity_code == "observation" else f"base_{entity_code}"
        origin_name = entity_import_field_name(entity_code, f"id_{suffix}_origin")
        id_name = f"id_{suffix}"  # identifiant de l'entité : nom nu
        uuid_name = entity_import_field_name(entity_code, f"uuid_{suffix}")
        fields += [
            _direct_bib_field(
                origin_name,
                f"Identifiant {label_entity}",
                id_destination,
                type_field="text",
                type_field_params={"attribut_label": f"Identifiant {label_entity}"},
                column_type=String,
                source_field=origin_name,
                dest_field=None,
            ),
            _direct_bib_field(
                id_name,
                f"ID {label_entity}",
                id_destination,
                type_field="number",
                type_field_params={
                    "step": 1.0,
                    "hidden": True,
                    "attribut_label": f"ID {label_entity}",
                },
                column_type=Integer,
                source_field=None,
                dest_field=id_name,
                autogenerated=True,
                display=False,
            ),
            _direct_bib_field(
                uuid_name,
                f"UUID {label_entity}",
                id_destination,
                type_field="text",
                type_field_params={"attribut_label": f"UUID {label_entity}"},
                column_type=Uuid,
                source_field=f"src_{uuid_name}",
                dest_field=uuid_name,
            ),
        ]

    geom_field_name = entity.data.get("geom_field_name")
    if entity_code == "site" and geom_field_name is not None:
        geom_name = entity.import_actions_class.get_field_name(geom_field_name)
        for coord, label in (("x", "Longitude (x)"), ("y", "Latitude (y)")):
            field_name = entity_import_field_name("site", coord)
            fields.append(
                _direct_bib_field(
                    field_name,
                    label,
                    id_destination,
                    type_field="number",
                    type_field_params={"attribut_label": label},
                    column_type=Float,
                    source_field=f"src_{field_name}",
                    dest_field=None,
                    mandatory=True,
                    optional_conditions=[geom_name],
                )
            )

    if entity_code == "visit":
        name = entity_import_field_name("visit", "uuid_dataset")
        fields.append(
            _direct_bib_field(
                name,
                "Identifiant JDD (UUID)",
                id_destination,
                type_field="text",
                type_field_params={"attribut_label": "Identifiant JDD (UUID)"},
                column_type=Uuid,
                source_field=f"src_{name}",
                dest_field=name,
                mandatory=True,
            )
        )

    return fields


def get_protocol_data(module_code: str, id_destination: int):
    """
    Construit les données du protocole à partir de la configuration v3 du module (`get_module`).

    Les champs de configuration suivent le chemin régulier (`prepare_fields`), y compris la géométrie du
    site (`optional_conditions` ajoutées par `monitoring_field_to_bib_field`). Les champs import only
    (identifiants propres, coordonnées x/y, UUID du JDD) sont des entrées de bib_fields directes sans
    store (`get_import_only_bib_fields`).

    Parameters
    ----------
    module_code : str
        Code du module.
    id_destination : int
        ID de la destination dans bib_destinations.

    Returns
    -------
    tuple
        Données du protocole et mapping des colonnes des entités.
    """
    # Import local : évite le cycle command.imports -> modules -> config -> command.imports
    from gn_module_monitoring.modules import get_module

    protocol_data = {}
    entity_hierarchy_map = {}
    module = get_module(module_code)
    entities = get_entities_protocol(module_code)

    tree = module["tree"]["module"]

    # Ensure all configurations are loaded in a dict (configuration v3 de chaque entité)
    entity_confs = {entity_code: module.entities[entity_code].data for entity_code in entities}

    # Now we can iterate safetly over confs
    for entity_code in entity_confs:
        entity = module.entities[entity_code]
        parent_entity = get_entity_parent(tree, entity_code)

        entity_hierarchy_map[entity_code] = {
            "id_field_name": entity.import_actions_class.ID_FIELD,
            "parent_entity": (
                parent_entity if parent_entity not in ENTITIES_NOT_AVAILABLE else None
            ),
        }
        parent_data = entity_confs.get(parent_entity, None)
        direct_fields = get_import_only_bib_fields(entity_code, entity, id_destination)
        skip = [field["name_field"] for field in direct_fields]
        protocol_data[entity_code] = prepare_fields(entity, id_destination, parent_data, skip=skip)
        protocol_data[entity_code]["fields"].extend(direct_fields)
        if entity_code in ("site", "sites_group"):
            protocol_data[entity_code]["display_properties"] = entity.data.get(
                "display_properties", []
            )

    # Add observation_detail the file exists
    if "observation_detail" in entities:

        entity_hierarchy_map["observation_detail"] = {
            "id_field_name": module.entities["observation_detail"].import_actions_class.ID_FIELD,
            "parent_entity": "observation",
        }
        parent_data = entity_confs.get("observation", None)
        protocol_data["observation_detail"] = prepare_fields(
            module.entities["observation_detail"], id_destination, parent_data
        )

    return protocol_data, entity_hierarchy_map


def get_existing_protocol_state(id_destination: int, module_data: dict):
    """
    Récupère l'état actuel du protocole en base de données.
    """
    fields_query = select(BibFields).filter_by(id_destination=id_destination)
    existing_fields = DB.session.execute(fields_query).scalars().all()

    entities_query = select(Entity).filter_by(id_destination=id_destination)
    existing_entities = DB.session.execute(entities_query).scalars().all()

    destination = DB.session.execute(
        select(Destination).filter_by(id_destination=id_destination)
    ).scalar()
    new_label = destination_name(module_data["module"].get("module_label"))

    return {
        "fields": [field.__dict__ for field in existing_fields],
        "entities": [entity.__dict__ for entity in existing_entities],
        "label": True if destination and destination.label != new_label else False,
    }


def update_protocol(
    module_data,
    module_code,
    fields_to_delete,
    update_label_only=False,
    recreate_transient_table=True,
):
    """
    Met à jour un protocole existant ou uniquement le libellé de l'entité dans `bib_entities`.

    Args:
        module_data: Données du module à mettre à jour.
        module_code: Code du module.
        fields_to_delete: Liste des champs à supprimer.
        update_label_only: Si vrai, met à jour uniquement le label de l'entité.
        recreate_transient_table: Si vrai, la table transitoire est recréée (écrase ses données).

    Returns:
        Booléen indiquant si la mise à jour a réussi.
    """
    try:
        module_label = module_data["module"].get("module_label")

        destination = DB.session.execute(
            select(Destination).filter_by(code=module_code)
        ).scalar_one()

        if update_label_only:
            destination.label = destination_name(module_label)
            update_entity_label(destination.id_destination, module_label)
            DB.session.commit()
            return True

        protocol_data, entity_hierarchy_map = get_protocol_data(
            module_code, destination.id_destination
        )

        with DB.session.begin_nested():

            destination.label = destination_name(module_label)

            insert_bib_field(protocol_data)

            insert_entities(
                protocol_data,
                destination.id_destination,
                entity_hierarchy_map,
                module_code=module_code,
            )

            insert_entity_field_relations(
                protocol_data, destination.id_destination, entity_hierarchy_map
            )

            if fields_to_delete:
                delete_bib_fields(fields_to_delete)

            if recreate_transient_table:
                create_sql_import_table_protocol(module_code, protocol_data)

        DB.session.commit()
        from gn_module_monitoring.modules import invalidate_module

        invalidate_module(module_code)
        return True

    except Exception as e:
        DB.session.rollback()
        print(f"Erreur lors de la mise à jour du protocole : {str(e)}")
        return False


def compare_protocol_fields(existing_fields, new_fields):
    """
    Compare les champs existants avec les nouveaux champs pour identifier les différences.

    Args:
        existing_fields: Liste des champs existants en base
        new_fields: Liste des nouveaux champs depuis les fichiers JSON

    Returns:
        - Liste des champs à ajouter
        - Liste des champs à mettre à jour
        - Liste des champs à supprimer
    """
    existing_by_name = {f["name_field"]: f for f in existing_fields}
    new_by_name = {f["name_field"]: f for f in new_fields}

    to_add = []
    to_update = []
    to_delete = []

    for name, new_field in new_by_name.items():
        if name not in existing_by_name:
            to_add.append(new_field)
        else:
            existing = existing_by_name[name]
            if has_field_changes(existing, new_field):
                to_update.append(new_field)

    for name in existing_by_name:
        if name not in new_by_name:
            to_delete.append(existing_by_name[name])

    return to_add, to_update, to_delete


# Attributs de bib_entities produits par la génération (insert_entities), comparés à l'existant.
ENTITY_COMPARED_ATTRS = [
    "label",
    "order",
    "validity_column",
    "destination_table_schema",
    "destination_table_name",
    "parent",
    "unique_field",
    "uuid_field",
]


def _entity_code_in_db(entity_code: str) -> str:
    """Code de l'entité dans bib_entities (insert_entities : observation_detail -> obs_detail)."""
    return "obs_detail" if entity_code == "observation_detail" else entity_code


def get_expected_entities(module_code: str, protocol_data: dict, entity_hierarchy_map: dict):
    """
    Entités attendues dans bib_entities, calculées comme le fait `insert_entities`.

    `parent`, `unique_field` et `uuid_field` sont des codes (et non des identifiants), pour être
    comparables à la base.
    """
    # Import local : évite le cycle command.imports -> modules -> config -> command.imports
    from gn_module_monitoring.modules.entities import ENTITY_MAP

    expected = []
    for order, entity_code in enumerate(get_entities_protocol(module_code), start=1):
        label = protocol_data[entity_code]["label"]
        parent = entity_hierarchy_map[entity_code]["parent_entity"]
        expected.append(
            {
                "code": _entity_code_in_db(entity_code),
                "label": label[:64] if label else entity_code,
                "order": order,
                "validity_column": f"{entity_code.lower()}_valid",
                "destination_table_schema": "gn_monitoring",
                "destination_table_name": TABLE_NAME_SUBMODULE.get(entity_code),
                "parent": _entity_code_in_db(parent) if parent else None,
                "unique_field": ENTITY_MAP[entity_code].import_actions_class.ID_FIELD,
                "uuid_field": ENTITY_MAP[entity_code].import_actions_class.UUID_FIELD,
            }
        )
    return expected


def get_existing_entities(id_destination: int) -> list:
    """Entités présentes en base (bib_entities) pour la destination, au même format que `get_expected_entities`."""
    entities = (
        DB.session.execute(select(Entity).filter_by(id_destination=id_destination)).scalars().all()
    )
    codes_by_id = {entity.id_entity: entity.code for entity in entities}
    field_names = dict(
        DB.session.execute(
            select(BibFields.id_field, BibFields.name_field).where(
                BibFields.id_destination == id_destination
            )
        ).all()
    )
    return [
        {
            "code": entity.code,
            "label": entity.label,
            "order": entity.order,
            "validity_column": entity.validity_column,
            "destination_table_schema": entity.destination_table_schema,
            "destination_table_name": entity.destination_table_name,
            "parent": codes_by_id.get(entity.id_parent),
            "unique_field": field_names.get(entity.id_unique_column),
            "uuid_field": field_names.get(entity.id_uuid_column),
        }
        for entity in entities
    ]


def compare_bib_entities(existing_entities: list, expected_entities: list) -> dict:
    """
    Compare bib_entities existantes aux entités attendues (clé : code de l'entité).

    Returns
    -------
    dict
        `added` (codes attendus absents), `removed` (codes existants non attendus, non supprimés
        automatiquement), `changed` (`{"code", "attr", "db", "expected"}`).
    """
    existing_by_code = {entity["code"]: entity for entity in existing_entities}
    expected_by_code = {entity["code"]: entity for entity in expected_entities}

    added = [code for code in expected_by_code if code not in existing_by_code]
    removed = [code for code in existing_by_code if code not in expected_by_code]
    changed = []
    for code, expected in expected_by_code.items():
        existing = existing_by_code.get(code)
        if existing is None:
            continue
        for attr in ENTITY_COMPARED_ATTRS:
            if existing.get(attr) != expected.get(attr):
                changed.append(
                    {
                        "code": code,
                        "attr": attr,
                        "db": existing.get(attr),
                        "expected": expected.get(attr),
                    }
                )
    return {"added": added, "removed": removed, "changed": changed}


def compute_protocol_diff(module_code: str, module_data: dict) -> dict:
    """
    Compare le protocole voulu (configuration v3 du module) à l'existant en base, sans rien écrire.

    Compare :
    - le libellé de la destination ;
    - `bib_fields` : champs ajoutés, modifiés (attributs concernés), supprimés ;
    - `bib_entities` : entités ajoutées, supprimées, modifiées ;
    - la table transitoire `gn_imports.t_imports_<module>` : colonnes ajoutées, supprimées, de type différent.

    Returns
    -------
    dict
        `module_code`, `label` (None ou `{"db", "expected"}`), `fields`
        (`added`, `updated` = `{"name_field", "changes", "new"}`, `deleted` = champs existants),
        `entities` (voir `compare_bib_entities`), `transient_table` (voir `get_transient_table_diff`).
    """
    destination = DB.session.execute(select(Destination).filter_by(code=module_code)).scalar_one()

    expected_label = destination_name(module_data["module"].get("module_label"))
    label = None
    if destination.label != expected_label:
        label = {"db": destination.label, "expected": expected_label}

    existing_state = get_existing_protocol_state(destination.id_destination, module_data)
    protocol_data, entity_hierarchy_map = get_protocol_data(
        module_code, destination.id_destination
    )

    all_new_fields = []
    for entity_fields in protocol_data.values():
        all_new_fields.extend(entity_fields["fields"])

    fields_to_add, fields_to_update, fields_to_delete = compare_protocol_fields(
        existing_state["fields"], all_new_fields
    )
    existing_by_name = {field["name_field"]: field for field in existing_state["fields"]}
    updated = [
        {
            "name_field": field["name_field"],
            "changes": get_field_changes(existing_by_name[field["name_field"]], field),
            "new": field,
        }
        for field in fields_to_update
    ]

    expected_entities = get_expected_entities(module_code, protocol_data, entity_hierarchy_map)
    existing_entities = get_existing_entities(destination.id_destination)

    return {
        "module_code": module_code,
        "label": label,
        "fields": {"added": fields_to_add, "updated": updated, "deleted": fields_to_delete},
        "entities": compare_bib_entities(existing_entities, expected_entities),
        "transient_table": get_transient_table_diff(module_code, protocol_data),
    }


def is_protocol_diff_empty(diff: dict) -> bool:
    """Vrai si rien ne diffère entre le protocole voulu et l'existant (y compris la table transitoire)."""
    entities = diff["entities"]
    return (
        diff["label"] is None
        and not diff["fields"]["added"]
        and not diff["fields"]["updated"]
        and not diff["fields"]["deleted"]
        and not entities["added"]
        and not entities["removed"]
        and not entities["changed"]
        and not transient_table_has_diff(diff["transient_table"])
    )


def format_protocol_diff(diff: dict) -> list:
    """Lignes lisibles décrivant toutes les différences d'un `compute_protocol_diff`."""
    lines = []
    if diff["label"] is not None:
        lines.append(
            f"Libellé de la destination : '{diff['label']['db']}' -> '{diff['label']['expected']}'"
        )

    fields = diff["fields"]
    if fields["added"]:
        names = ", ".join(f["name_field"] for f in fields["added"])
        lines.append(f"bib_fields à ajouter ({len(fields['added'])}) : {names}")
    for updated in fields["updated"]:
        details = "; ".join(
            f"{change['attr']} : {change['db']!r} -> {change['expected']!r}"
            for change in updated["changes"]
        )
        lines.append(f"bib_fields à modifier {updated['name_field']} : {details}")
    if fields["deleted"]:
        names = ", ".join(f["name_field"] for f in fields["deleted"])
        lines.append(f"bib_fields à supprimer ({len(fields['deleted'])}) : {names}")

    entities = diff["entities"]
    for code in entities["added"]:
        lines.append(f"bib_entities à ajouter : {code}")
    for code in entities["removed"]:
        lines.append(
            f"bib_entities absente de la configuration (non supprimée automatiquement) : {code}"
        )
    for change in entities["changed"]:
        lines.append(
            f"bib_entities {change['code']} : {change['attr']} : "
            f"{change['db']!r} -> {change['expected']!r}"
        )

    transient = diff["transient_table"]
    if not transient["exists"]:
        lines.append(
            f"Table transitoire {transient['table']} absente : sera créée "
            f"({len(transient['added'])} colonnes)"
        )
    else:
        if transient["added"]:
            lines.append(
                f"Table transitoire {transient['table']} : colonnes à ajouter : "
                f"{', '.join(transient['added'])}"
            )
        if transient["removed"]:
            lines.append(
                f"Table transitoire {transient['table']} : colonnes à supprimer : "
                f"{', '.join(transient['removed'])}"
            )
        for change in transient["type_changed"]:
            lines.append(
                f"Table transitoire {transient['table']} : type de {change['name']} : "
                f"{change['db']} -> {change['expected']}"
            )
    return lines
